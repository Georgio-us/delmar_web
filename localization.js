const reverseDictionary = new Map(languagePairs.map(([ru, uk]) => [uk, ru]))
const escapePhrase = text => text.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
function phraseRules(map) {
  return [...map.entries()].sort((a,b) => b[0].length-a[0].length).map(([from,to]) => [new RegExp(`(?<![\\p{L}])${escapePhrase(from)}(?![\\p{L}])`,'gu'),to])
}
const ukrainianRules = phraseRules(dictionary)
const russianRules = phraseRules(reverseDictionary)
function translateText(text, language) {
  if (language === 'uk' && dictionary.has(text.trim())) return text.replace(text.trim(),dictionary.get(text.trim()))
  if (language === 'ru' && reverseDictionary.has(text.trim())) return text.replace(text.trim(),reverseDictionary.get(text.trim()))
  let result = text
  for (const [pattern,replacement] of language === 'uk' ? ukrainianRules : russianRules) result = result.replace(pattern,replacement)
  if (language === 'uk') result = result.replace(/^От /,'Від ')
  else result = result.replace(/^Від /,'От ')
  return result
}
