const languageObserver = new MutationObserver(records => {
  languageObserver.disconnect()
  for (const record of records) {
    if (record.type === 'attributes') localizeAttributes(record.target)
    else if (record.type === 'characterData') localizeTextNode(record.target)
    else for (const node of record.addedNodes) localizeBranch(node)
  }
  observeLanguageChanges()
})
function skipLocalization(element) { return element.closest('script,style,[data-no-i18n],textarea') }
function localizeTextNode(node) {
  if (!node.parentElement || skipLocalization(node.parentElement) || !node.textContent.trim()) return
  const record = textSources.get(node)
  const source = record && record.last === node.textContent ? record.source : translateText(node.textContent,'ru')
  const target = currentLanguage === 'ru' ? source : translateText(source,'uk')
  if (node.textContent !== target) node.textContent = target
  textSources.set(node,{source,last:target})
}
function localizeAttributes(element) {
  if (skipLocalization(element)) return
  const records = attributeSources.get(element) || {}
  for (const attribute of ['aria-label','placeholder','alt']) {
    if (!element.hasAttribute(attribute)) continue
    const value = element.getAttribute(attribute), record = records[attribute]
    const source = record && record.last === value ? record.source : translateText(value,'ru')
    const target = currentLanguage === 'ru' ? source : translateText(source,'uk')
    if (value !== target) element.setAttribute(attribute,target)
    records[attribute] = {source,last:target}
  }
  attributeSources.set(element,records)
}
function localizeBranch(root) {
  if (root.nodeType === Node.TEXT_NODE) { localizeTextNode(root); return }
  if (root.nodeType !== Node.ELEMENT_NODE || skipLocalization(root)) return
  const walker = document.createTreeWalker(root,NodeFilter.SHOW_TEXT)
  const nodes = []
  while(walker.nextNode()) nodes.push(walker.currentNode)
  nodes.forEach(localizeTextNode)
  localizeAttributes(root)
  root.querySelectorAll('[aria-label],[placeholder],[alt]').forEach(localizeAttributes)
}
function observeLanguageChanges() {
  languageObserver.observe(document.body,{childList:true,subtree:true,characterData:true,attributes:true,attributeFilter:['aria-label','placeholder','alt']})
}
function localizeDOM() {
  languageObserver.disconnect()
  localizeBranch(document.body)
  document.documentElement.lang = currentLanguage
  const title = currentLanguage === 'uk' ? 'DELMAR GROUP — агенція нерухомості в Одесі' : 'DELMAR GROUP - агентство недвижимости в Одессе'
  if (document.title !== title) document.title = title
  observeLanguageChanges()
}
